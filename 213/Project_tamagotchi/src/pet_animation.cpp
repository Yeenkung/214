void AnimationPet_hunger(Adafruit_SSD1306 &display) {
// สลับเฟรมทุกๆ 500 ms
  static unsigned long lastFrameTime = 0;
  static int sequenceIndex = 0;

  // ลำดับการเล่นเฟรม: frame0, frame2 ทำซ้ำ 3 ครั้ง แล้วตามด้วย frame1, frame3 ทำ 1 ครั้ง
  // [0, 2, 0, 2, 0, 2, 1, 3] ทั้งหมด 8 จังหวะ
  const int frameSequence[] = {0, 2, 0, 2, 0, 2, 1, 3};
  const int totalFrames = sizeof(frameSequence) / sizeof(frameSequence[0]);

  // เช็คเวลาถ้าผ่านไปครบ 500 ms ให้เลื่อนไปเฟรมถัดไป
  if (millis() - lastFrameTime >= 750) {
    sequenceIndex = (sequenceIndex + 1) % totalFrames; // วนลูปกลับไปที่ 0 เมื่อครบ 8 จังหวะ
    lastFrameTime = millis();
  }

  // เลือกเฟรมภาพจากลำดับปัจจุบัน
  int currentFrame = frameSequence[sequenceIndex];
  const uint8_t* frameToDraw = frame0;

  if (currentFrame == 1) frameToDraw = frame1;
  else if (currentFrame == 2) frameToDraw = frame2;
  else if (currentFrame == 3) frameToDraw = frame3;

  // วาด Bitmap ขนาด 128x64 พิกเซล ลงบนหน้าจอ OLED
  display.drawBitmap(0, 0, frameToDraw, 128, 64, SSD1306_WHITE);
}

void AnimationPet_happy(Adafruit_SSD1306 &display) {
  static unsigned long lastFrameTime = 0;
  static int currentFrame = 0;

  if (millis() - lastFrameTime > 200) { // ขยับเร็วกว่าปกติเมื่อมีความสุข
    currentFrame = (currentFrame + 1) % 2;
    lastFrameTime = millis();
  }

  const uint8_t* frameToDraw = (currentFrame == 0) ? frame0 : frame2;
  display.drawBitmap(0, 0, frameToDraw, 128, 64, SSD1306_WHITE);
}

void AnimationPet_clean(Adafruit_SSD1306 &display) {
  static unsigned long lastFrameTime = 0;
  static int currentFrame = 0;

  if (millis() - lastFrameTime > 400) {
    currentFrame = (currentFrame + 1) % 2;
    lastFrameTime = millis();
  }

  const uint8_t* frameToDraw = (currentFrame == 0) ? frame0 : frame1;
  display.drawBitmap(0, 0, frameToDraw, 128, 64, SSD1306_WHITE);
}